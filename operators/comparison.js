/* 
COMPARISON OPERATORS
Comparison operators compare two values and return a Boolean result: true or false
*/

// > - Greater than
console.log(5 > 3);
// < - Less than

console.log(5 < 3);
// >= - Greater than or equal to
console.log(5 >= 5);
// <= - Lesser than or equal to
console.log(4 <= 5);
// == - Loose equality
console.log(5 == "5");
// == - Strict equality
console.log(5 === "5");
// != - Loose inequality
console.log(5 != "5");
// !== - Strict inequality
console.log(5 !== "5");


console.log("10" > 5); // true
console.log("10" > "5"); // false