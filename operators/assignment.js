/* 
ASSIGNMENT OPERATORS
Assignment operators assign values to variables or update their existing values
*/

// Basic Assignment
let y = 5;
// Here, = assigns the value 10 to y. It does not mean "equal to" in the mathematical comparison sense 

// Compund assignment operators
let x = 10;

x +=5; // x = x + 5
console.log(x);

x -=5; // x = x - 5
console.log(x);

x *= 5; // x = x * 5
console.log(x);

x /= 5; // x = x / 5
console.log(x);

x %= 5; // x = x % 5
console.log(x);

x **= 2; // x = x ** 2
console.log(x);